var ball="playerBall";
var lifemax=0;
var explosionrange=0;

function shopReady(){
    
    $(".bullet").text("selected");
    $(".bullet").attr("disabled",true);
    $(".bullet").click(function(){
        ball="bullet";
        game.selectBall(0);
        $(this).text("selected");
        $(this).attr("disabled",true);
        if($(".cannon").text()=="selected"){
            $(".cannon").text("select");
            $(".cannon").attr("disabled",false);
        }
        if($(".lazer").text()=="selected"){
            $(".lazer").text("select");
            $(".lazer").attr("disabled",false);
        }
    })
    $(".cannon").click(function(){
        if($(this).text()=="1000g"){
            if(game.coin>=1000){
                $(this).text("select");
                game.coin-=1000;
                if(this.coin>=1000){
                    $(".money").text(Math.floor(this.coin/1000)+"kg");
                }
                else{
                    $(".money").text(this.coin+"g");
                }
            }
       }
        else{
            ball="cannon";
            game.selectBall(1);
            $(this).text("selected");
            $(this).attr("disabled",true);
            if($(".lazer").text()=="selected"){
                $(".lazer").text("select");
                $(".lazer").attr("disabled",false);
            }
            if($(".bullet").text()=="selected"){
                $(".bullet").text("select");
                $(".bullet").attr("disabled",false);
            }
        }
    })
    $(".lazer").click(function(){
        if($(this).text()=="1000g"){
            if(game.coin>=1000){
                $(this).text("select");
                if(this.coin>=1000){
                    $(".money").text(Math.floor(this.coin/1000)+"kg");
                }
                else{
                    $(".money").text(this.coin+"g");
                }
            }
        }
        else{
            ball="lazer";
            game.selectBall(2);
            $(this).text("selected");
            $(this).attr("disabled",true);
            if($(".cannon").text()=="selected"){
                $(".cannon").text("select");
                $(".cannon").attr("disabled",false);
            }
            if($(".bullet").text()=="selected"){
                $(".bullet").text("select");
                $(".bullet").attr("disabled",false);
            }
        }
    })
    $("#lifeaddition").click(function(){
        if(game.coin>=1000){
            lifemax+=1;
            $("#lifemax").text("생명 최대량 추가("+(3-lifemax)+"/3)");
            buy_maxHealth(lifemax);
            if(lifemax==3){
                $(this).text("sold out");
                $(this).attr("disabled",true);
            }
            game.coin-=1000;
            if(this.coin>=1000){
                $(".money").text(Math.floor(this.coin/1000)+"kg");
            }
            else{
                $(".money").text(this.coin+"g");
            }
        }
    })
    $("#lifepurchase").click(function(){
        if(game.coin>=500){
            buy_regeneration();
            game.coin-=500;
            if(this.coin>=1000){
                $(".money").text(Math.floor(this.coin/1000)+"kg");
            }
            else{
                $(".money").text(this.coin+"g");
            }
        }
    })
    $("#shieldpurchase").click(function(){
        if(game.coin>=2000){
            buy_shield();
            game.coin-=2000;
            if(this.coin>=1000){
                $(".money").text(Math.floor(this.coin/1000)+"kg");
            }
            else{
                $(".money").text(this.coin+"g");
            }
        }
    })
    $("#parringtime").click(function(){
        if(game.coin>=500){
            buy_parryCool();
            game.coin-=500;
            if(this.coin>=1000){
                $(".money").text(Math.floor(this.coin/1000)+"kg");
            }
            else{
                $(".money").text(this.coin+"g");
            }
        }
    })
    $("#explosionrange").click(function(){
        if(game.coin>=500){
            buy_explodeUp();
            game.coin-=500;
            if(this.coin>=1000){
                $(".money").text(Math.floor(this.coin/1000)+"kg");
            }
            else{
                $(".money").text(this.coin+"g");
            }
        }
    })
    $("#reloadtime").click(function(){
        if(game.coin>=1000){
            buy_reloadCool();
            game.coin-=1000;
            if(this.coin>=1000){
                $(".money").text(Math.floor(this.coin/1000)+"kg");
            }
            else{
                $(".money").text(this.coin+"g");
            }
        }
    })
    $("#stealthpurchase").click(function(){
        if(game.coin>=2000){
            buy_hidingSkill();
            game.coin-=2000;
            if(this.coin>=1000){
                $(".money").text(Math.floor(this.coin/1000)+"kg");
            }
            else{
                $(".money").text(this.coin+"g");
            }
        }
    })
}

function soldout(par){
    for(var i=1; i<=4; i++){
        var id="#"+par+" .strongpo"+i;
        $(id).text("sold out");
        $(id).attr("disabled",true);
    }
}